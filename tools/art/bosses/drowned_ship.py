"""Drowned Elder, session 8: ship the model, write its Mythic mob and cosmetic skills, and the rig table the fight reads.

- src/main/models/occultech_drowned_elder.bbmodel: the final rig (session 7: the painted model with its four hitboxes,
  glow bones and every clip), carrying the **neutral** eyes (session 6): the fight tints them per state.
- src/main/mythic/Mobs/DrownedElder.yml and Skills/DrownedElder.yml: look and sound only. DrownedElder.java decides
  when each runs and deals every hit.
- src/main/java/.../boss/tier2/DrownedElderRig.java (generated): where the model's parts are, in blocks from the
  carrier's feet (ahead, up, right), at the moments the fight needs: each beam eye through the aim clip (the beams leave
  the eyes), the head's eye at the stare's pulse, the two holes of the surge, a point on the body where guardians shed.
- Refuses to ship with faces that would flicker, or with half-clear texels.

Run from the repository root after drowned_s7.py, with the folder holding assets/ from the 26.2 client as the last
argument: python tools/art/bosses/drowned_ship.py <folder>
"""
import base64
import io
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "tools" / "art"))
from bosskit.checks import flicker_pairs  # noqa: E402
from bosses import drowned_s3 as s3, drowned_s7 as s7  # noqa: E402

S7 = ROOT / "docs/art/bosses/drowned_elder/overhaul/s7_animation"
MODELS = ROOT / "src/main/models"
SKILLS = ROOT / "src/main/mythic/Skills/DrownedElder.yml"
MOBS = ROOT / "src/main/mythic/Mobs/DrownedElder.yml"
RIG_JAVA = ROOT / "src/main/java/io/github/amitelia/occultech/boss/tier2/DrownedElderRig.java"
NAME = "occultech_drowned_elder"
EYES = (2, 4, 6)
BEAM = {"CALM": "6EE8CE", "LOCK": "D6FFF6", "SURGED": "6EA0FF"}       # session 6
HEAD = {"CALM": "ECE6DC", "STARE": "8CFFE4"}
DEAD = {"beam": "282C30", "head": "343236"}
AIM_FRAMES = [round(0.2 * i, 2) for i in range(11)]                      # 0 .. 2.0 s, the aim clip up to its contact


def check(rig):
    clash = flicker_pairs([c for c in s3.build(None).cubes if c.mat != "hitbox"])
    if clash:
        raise SystemExit(f"faces that would flicker in game: {clash[:5]}")
    for tex in rig["textures"]:
        a = np.array(Image.open(io.BytesIO(base64.b64decode(tex["source"].split(",", 1)[1]))).convert("RGBA"))[..., 3]
        if ((a > 0) & (a < 255)).any():
            raise SystemExit("half-clear texels")


def ship():
    rig = json.loads((S7 / f"{NAME}_rig.bbmodel").read_text(encoding="utf-8"))
    check(rig)
    rig["name"] = NAME
    for tex in rig["textures"]:
        tex["name"] = f"{NAME}.png"
    (MODELS / f"{NAME}.bbmodel").write_text(json.dumps(rig, separators=(",", ":")) + "\n", encoding="utf-8")
    hit = sum(1 for g in rig["groups"] if g["name"].startswith("ob_"))
    return {"animations": sorted(a["name"] for a in rig["animations"]), "elements": len(rig["elements"]), "hitboxes": hit}


# ---- where the parts are --------------------------------------------------------------------------------------------------

def centre(m, name):
    return next(c for c in m.cubes if c.name == name).corners().mean(0)


def blocks(p):
    """Model units -> (ahead, up, right) in blocks from the carrier's feet: the model faces -z, its right is +x."""
    return (round(-p[2] / 16, 3), round(p[1] / 16, 3), round(p[0] / 16, 3))


def frame(clip, t):
    return s7.posed(s7.CLIPS[clip][2](t, s7.shapes()))


def table():
    eyes = []                                   # [eye][side][frame]
    posed = [frame("aim", t) for t in AIM_FRAMES]
    for i in EYES:
        eyes.append([[blocks(centre(m, f"seg{i}_eye{side}")) for m in posed] for side in ("r", "l")])
    stare = frame("stare", 1.0)
    dive = frame("dive", 1.0)
    swim = frame("idle", 0.0)
    P, marks = s7.surge_path(), s7.marks()
    hole_b = P.at(P.face0 + marks["out"])
    return {
        "eyes": eyes,
        "stare_eye": blocks(centre(stare, "eye")),
        "hole_a": blocks(centre(dive, "head")),
        "hole_b": blocks(hole_b),
        "shed": blocks(centre(swim, "seg5")),
        "head": blocks(centre(swim, "head")),
    }


def java(t):
    def vec(v):
        return "{" + ", ".join(f"{x}" for x in v) + "}"

    eyes = ",\n".join("        {" + ", ".join("{" + ", ".join(vec(v) for v in side) + "}" for side in eye) + "}"
                      for eye in t["eyes"])
    frames = ", ".join(str(f) for f in AIM_FRAMES)
    return f"""package io.github.amitelia.occultech.boss.tier2;

/**
 * Where the Drowned Elder model's parts are, in blocks from the carrier's feet, as {{ahead, up, right}} for the carrier
 * facing its body yaw. Generated by tools/art/bosses/drowned_ship.py from the session 7 clips; do not edit by hand.
 */
final class DrownedElderRig {{
    private DrownedElderRig() {{}}

    /** Seconds into the aim clip that {{@link #EYES}} samples (the beams fire at the last one). */
    static final double[] AIM_FRAMES = {{{frames}}};

    /** [beam eye: segments 3, 5, 7][side][aim frame] - each eye's two sides through the aim clip. */
    static final double[][][][] EYES = {{
{eyes}
    }};

    /** The head's great eye at the stare's pulse (1.0 s). */
    static final double[] STARE_EYE = {vec(t["stare_eye"])};
    /** The dive's hole: the head as it meets the floor (1.0 s). The waves start here. */
    static final double[] HOLE_A = {vec(t["hole_a"])};
    /** The emerge's hole: where the head breaks back out of the floor. */
    static final double[] HOLE_B = {vec(t["hole_b"])};
    /** The middle of the body while swimming: guardians shed from here. */
    static final double[] SHED = {vec(t["shed"])};
    /** The head's centre while swimming. */
    static final double[] HEAD = {vec(t["head"])};
}}
"""


# ---- Mythic -----------------------------------------------------------------------------------------------------------------

def tint(bone, colour):
    return f"  - tint{{m={NAME};p={bone};c={colour}}} @self"


def beams(colour):
    return [tint(f"glow_eye{i}", colour) for i in EYES]


def skill(name, lines):
    return [f"{name}:", "  Skills:"] + lines + [""]


def skills():
    out = ["# Look and sound only. DrownedElder.java decides when each of these runs and deals every hit.",
           "# Generated by tools/art/bosses/drowned_ship.py. The eyes are painted neutral and tinted per state (session 6):",
           "# the three beam eyes calm / lock / surged, the head's great eye calm / stare; all dark when dead.", ""]
    out += skill("DROWNED_ELDER_AIM", [f"  - state{{m={NAME};s=aim}} @self",
                                       "  - sound{s=entity.elder_guardian.ambient;v=2;p=0.6} @self"])
    out += skill("DROWNED_ELDER_LOCK", beams(BEAM["LOCK"]) + ["  - sound{s=entity.guardian.attack;v=2;p=0.5} @self"])
    out += skill("DROWNED_ELDER_STARE", [f"  - state{{m={NAME};s=stare}} @self", tint("glow_eye", HEAD["STARE"])])
    out += skill("DROWNED_ELDER_PULSE", ["  - sound{s=entity.elder_guardian.curse;v=2;p=0.8} @self"])
    out += skill("DROWNED_ELDER_STARE_END", [tint("glow_eye", HEAD["CALM"])])
    out += skill("DROWNED_ELDER_SHED", [f"  - state{{m={NAME};s=shed}} @self",
                                        "  - sound{s=entity.elder_guardian.flop;v=2;p=0.5} @self"])
    out += skill("DROWNED_ELDER_DIVE", [f"  - state{{m={NAME};s=dive}} @self",
                                        "  - sound{s=entity.elder_guardian.ambient;v=2.5;p=0.4} @self", "  - delay 20",
                                        "  - sound{s=entity.generic.splash;v=2.5;p=0.5} @self"])
    out += skill("DROWNED_ELDER_EMERGE", [f"  - state{{m={NAME};s=emerge}} @self", "  - delay 14",
                                          "  - sound{s=entity.generic.splash;v=2.5;p=0.6} @self", "  - delay 14",
                                          "  - sound{s=entity.elder_guardian.ambient;v=2.5;p=0.5} @self"])
    out += skill("DROWNED_ELDER_FLINCH", [f"  - state{{m={NAME};s=flinch}} @self"])
    out += skill("DROWNED_ELDER_STATE_CALM", beams(BEAM["CALM"]) + [tint("glow_eye", HEAD["CALM"])])
    out += skill("DROWNED_ELDER_STATE_SURGED", beams(BEAM["SURGED"]) + [tint("glow_eye", HEAD["CALM"])])
    out += skill("DROWNED_ELDER_DEATH", ["  - sound{s=entity.elder_guardian.death;v=2.5;p=0.6} @self"]
                 + beams(DEAD["beam"]) + [tint("glow_eye", DEAD["head"])])
    return "\n".join(out)


def mobs():
    return "\n".join([
        "# The Drowned Elder's body: the Abyssal Serpent model on an invisible elder guardian at the floor.",
        "# Occultech steers it, decides every beam, stare, shed and surge, deals all damage (DrownedElder.java) and hands",
        "# out loot. Health is the solo value; Occultech multiplies it for the group after the spawn.", "",
        "OCCULTECH_DROWNED_ELDER:", "  Type: ELDER_GUARDIAN", "  Display: '&5Drowned Elder'", "  Health: 500", "  Damage: 0",
        "  Armor: 0", "  Options:", "    # Occultech rebuilds the fight from its saved state; Mythic never restores it",
        "    Despawn: true", "    PreventOtherDrops: true", "    PreventMobKillDrops: true", "    PreventItemPickup: true",
        "    KnockbackResistance: 1", "    FollowRange: 40", "    Silent: true", "    AlwaysShowName: true", "  Drops: []",
        "  Skills:", f"  - model{{m={NAME}}} @self ~onSpawn", f"  - state{{m={NAME};s=spawn}} @self ~onSpawn",
        "  - bodyrotation{mh=10;mnh=-10;rde=0;rdu=3} @self ~onSpawn",
        "  - skill{s=DROWNED_ELDER_STATE_CALM} @self ~onSpawn", "  - skill{s=DROWNED_ELDER_DEATH} @self ~onDeath", ""])


def main():
    print(json.dumps(ship(), indent=1))
    t = table()
    RIG_JAVA.write_text(java(t), encoding="utf-8")
    print(json.dumps({k: v for k, v in t.items() if k != "eyes"}, indent=1))
    print("eye 3 right side through the aim:", t["eyes"][0][0])
    SKILLS.write_text(skills(), encoding="utf-8")
    MOBS.write_text(mobs(), encoding="utf-8")


if __name__ == "__main__":
    main()
