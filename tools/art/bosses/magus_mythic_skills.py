"""The Masquerade, session 8: writes his cosmetic Mythic skills (src/main/mythic/Skills/Masquerade.yml).

Look and sound only: Masquerade.java decides when each skill runs and deals every hit. It runs every gesture on him
and on each of his reflections at the same moment (they wear the same model, so `m=occultech_masquerade` works on
both). His states (session 6) are BetterModel tints: his eyes calm, flaring for a tell, out at death; a struck
reflection flashes icy over every bone before it breaks. Each tint is applied again 12 ticks later, after any hit
flash (BetterModel restores a bone's previous tint when a flash ends).

Run from the repository root: python tools/art/bosses/magus_mythic_skills.py
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "tools" / "art"))
from bosses import magus_s2 as s2  # noqa: E402

OUT = ROOT / "src/main/mythic/Skills/Masquerade.yml"
M = "occultech_masquerade"
TINTS = {"CALM": "78848E", "TELL": "FFFFFF", "DEAD": "282C30", "SHATTER": "AAE1FF"}


def eyes(colour):
    return [f"  - tint{{m={M};p=glow_eyes;c={colour}}} @self"]


def every_bone(colour, but=()):
    s2.MASK = "clown"
    bones = [g.name for g in s2.build("bones").groups if g.name not in but]
    return [f"  - tint{{m={M};p={bone};c={colour}}} @self" for bone in bones]


def state(clip):
    return [f"  - state{{m={M};s={clip}}} @self"]


def skills():
    out = ["# Look and sound only. Masquerade.java decides when each of these runs and deals every hit; it runs each",
           "# gesture on him and on every reflection at once (they wear his model), so only his sparkle tells them apart.",
           "# Generated by tools/art/bosses/magus_mythic_skills.py.",
           "# His eyes: calm 78848E (dimmed), the tell FFFFFF (the flare: the prism, the snap), dead 282C30. A struck",
           "# reflection flashes AAE1FF over every bone before it breaks. Each is applied again 12 ticks later.", ""]
    out += ["MASQUERADE_STATE_CALM:", "  Skills:"] + eyes(TINTS["CALM"]) + ["  - delay 12"] + eyes(TINTS["CALM"])
    out += ["MASQUERADE_THROW:", "  Skills:"] + state("throw")
    out += ["MASQUERADE_PRISM:", "  Skills:"] + state("prism") + eyes(TINTS["TELL"])
    out += ["  - sound{s=block.amethyst_block.chime;v=1.4;p=0.6} @self",
            "  - particles{p=end_rod;a=10;hs=0.6;vs=1.2;s=0.02;y=4.2} @self", "  - delay 12"] + eyes(TINTS["TELL"])
    out += ["  - delay 30"] + eyes(TINTS["CALM"]) + ["  - delay 12"] + eyes(TINTS["CALM"])
    out += ["MASQUERADE_CURTSEY:", "  Skills:"] + state("curtsey")
    out += ["  - sound{s=entity.illusioner.prepare_mirror;v=1.4;p=0.7} @self"]
    out += ["MASQUERADE_BLINK:", "  Skills:"] + state("blink")
    out += ["MASQUERADE_LAUGH:", "  Skills:"] + state("laugh") + eyes(TINTS["TELL"])
    out += ["  - sound{s=entity.witch.celebrate;v=1.6;p=0.5} @self", "  - delay 12"] + eyes(TINTS["TELL"])
    out += ["  - delay 14"] + eyes(TINTS["CALM"]) + ["  - delay 12"] + eyes(TINTS["CALM"])
    out += ["MASQUERADE_SNAP:", "  Skills:"] + state("snap") + eyes(TINTS["TELL"])
    out += ["  - delay 12", "  - sound{s=block.note_block.hat;v=2;p=1.6} @self"] + eyes(TINTS["TELL"])
    out += ["  - delay 20"] + eyes(TINTS["CALM"]) + ["  - delay 12"] + eyes(TINTS["CALM"])
    out += ["MASQUERADE_FLINCH:", "  Skills:"] + state("flinch")
    # the clean tint, run by Masquerade.java once BetterModel's hit flash is over: the flash restores each bone's
    # previous tint when it ends, and a tint that lands during it records the red as that previous tint - so the
    # model could stay red. Every bone back to untinted, then the eyes (EYES_TELL or EYES_CALM, once).
    out += ["MASQUERADE_UNTINT:", "  Skills:"] + every_bone("FFFFFF", but=("glow_eyes",))
    out += ["MASQUERADE_EYES_TELL:", "  Skills:"] + eyes(TINTS["TELL"])
    out += ["MASQUERADE_EYES_CALM:", "  Skills:"] + eyes(TINTS["CALM"])
    out += ["MASQUERADE_SHATTER:", "  Skills:"] + every_bone(TINTS["SHATTER"])
    out += ["MASQUERADE_DEATH:", "  Skills:"] + state("death") + eyes(TINTS["DEAD"])
    out += ["  - sound{s=entity.illusioner.death;v=1.6;p=0.6} @self",
            "  - sound{s=block.note_block.didgeridoo;v=1;p=0.5} @self", ""]
    return "\n".join(out)


if __name__ == "__main__":
    OUT.write_text(skills(), encoding="utf-8")
    print(OUT)
