"""The Archevoker, session 8: writes his Mythic mobs and cosmetic skills (src/main/mythic/Mobs|Skills/Archevoker.yml).

Look and sound only: Archevoker.java decides when each skill runs and deals every hit. His glows (eyes, ring, runes)
and each hand's (eye, spell circle) are painted neutral white (session 6) and tinted per state; each tint is applied
again 12 ticks later, after any hit flash (BetterModel restores a bone's previous tint when a flash ends).

Run from the repository root: python tools/art/bosses/archevoker_mythic_skills.py (after archevoker_ship.py)
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SKILLS = ROOT / "src/main/mythic/Skills/Archevoker.yml"
MOBS = ROOT / "src/main/mythic/Mobs/Archevoker.yml"
MODEL = ROOT / "src/main/models/occultech_archevoker.bbmodel"
M = "occultech_archevoker"
B = "ARCHEVOKER"
GLOW = ("glow_eyes", "glow_ring", "glow_runes")
STATES = {"CALM": "50DCFA", "TELL": "C8FAFF", "WOUNDED": "3696B0", "CAUGHT": "FFE8A0", "RISEN": "CE60FF"}
DEAD = "2E3038"
HANDS = {"CYAN": {"CALM": "50DCFA", "TELL": "C8FAFF"}, "PURPLE": {"CALM": "BA68FF", "TELL": "E8C4FF"}}


def tint(model, bones, colour):
    return [f"  - tint{{m={model};p={bone};c={colour}}} @self" for bone in bones]


def twice(lines):
    return lines + ["  - delay 12"] + lines


def skills():
    bones = [g["name"] for g in json.loads(MODEL.read_text(encoding="utf-8"))["groups"]
             if g["name"] not in GLOW and g["name"] != "ob_hitbox"]
    out = ["# Look and sound only. Archevoker.java decides when each of these runs and deals every hit.",
           "# Generated by tools/art/bosses/archevoker_mythic_skills.py.",
           "# His glows (eyes, ring, runes) are painted neutral and tinted: calm 50DCFA (spirit cyan), the tell C8FAFF,",
           "# wounded 3696B0 (one hand dead), caught FFE8A0 (cheating death), risen CE60FF (both hands dead), dead 2E3038.",
           "# The hands: cyan 50DCFA / tell C8FAFF, purple BA68FF / tell E8C4FF.", ""]
    for name, colour in STATES.items():
        out += [f"{B}_STATE_{name}:", "  Skills:"] + twice(tint(M, GLOW, colour))
    out += [f"{B}_UNTINT:", "  Skills:"] + tint(M, bones, "FFFFFF")
    for clip, sound in (("LINE", "entity.evoker.prepare_attack;v=2;p=0.8"),
                        ("RING", "entity.evoker.prepare_attack;v=2;p=0.7"),
                        ("SPIRAL", "entity.evoker.prepare_wololo;v=2;p=0.7"),
                        ("BURST", "entity.evoker.prepare_attack;v=2;p=1.3"),
                        ("RISEN_CAST", "entity.evoker.prepare_summon;v=2;p=0.6")):
        out += [f"{B}_{clip}:", "  Skills:", f"  - state{{m={M};s={clip.lower()}}} @self", f"  - sound{{s={sound}}} @self"]
    out += [f"{B}_FOLD:", "  Skills:", f"  - state{{m={M};s=idle_fold}} @self"]
    out += [f"{B}_FLINCH:", "  Skills:", f"  - state{{m={M};s=flinch}} @self"]
    out += [f"{B}_HAND_LOST:", "  Skills:", f"  - state{{m={M};s=hand_lost}} @self",
            "  - sound{s=entity.evoker.hurt;v=2;p=0.6} @self"]
    out += [f"{B}_CAUGHT:", "  Skills:", f"  - state{{m={M};s=caught}} @self"] + tint(M, GLOW, STATES["CAUGHT"])
    out += ["  - particles{p=totem_of_undying;a=40;hs=1.2;vs=1.4;s=0.3;y=4} @self", "  - delay 12"]
    out += tint(M, GLOW, STATES["CAUGHT"])
    out += [f"{B}_RISE:", "  Skills:", f"  - state{{m={M};s=rise}} @self", "  - delay 40",
            f"  - state{{m={M};s=risen_idle}} @self"] + twice(tint(M, GLOW, STATES["RISEN"]))
    out += [f"{B}_DEATH:", "  Skills:", f"  - state{{m={M};s=death}} @self"] + tint(M, GLOW, DEAD)
    out += ["  - sound{s=entity.evoker.death;v=2;p=0.5} @self"]
    for colour, tints in HANDS.items():
        hm = f"occultech_archevoker_hand_{colour.lower()}"
        out += [f"{B}_HAND_{colour}_CALM:", "  Skills:"] + twice(tint(hm, ("glow_eye", "glow_circle"), tints["CALM"]))
        out += [f"{B}_HAND_{colour}_TELL:", "  Skills:", f"  - state{{m={hm};s=tell}} @self",
                "  - sound{s=block.amethyst_block.resonate;v=1.6;p=0.7} @self"]
        out += twice(tint(hm, ("glow_eye", "glow_circle"), tints["TELL"]))
        out += [f"{B}_HAND_{colour}_HIT:", "  Skills:", f"  - state{{m={hm};s=hit}} @self"]
    return "\n".join(out) + "\n"


MOB = """# The Archevoker's body: an illager dark priest in a hood on a floating woodland-mansion throne, a ring of small
# gilded hands turning behind it. Occultech still decides every attack and every step, deals all damage
# (Archevoker.java) and hands out loot. Health is the solo value; Occultech multiplies it for the group after the spawn.
# The carrier is an evoker with its own mind taken away (no vexes, no fangs of its own); invisible, it draws nothing.
OCCULTECH_ARCHEVOKER:
  Type: EVOKER
  Display: '&5Archevoker'
  Health: 700
  Damage: 0
  Armor: 0
  Options:
    # Occultech rebuilds the body from its saved fight state; Mythic never restores it
    Despawn: true
    PreventOtherDrops: true
    PreventMobKillDrops: true
    PreventItemPickup: true
    KnockbackResistance: 0.8
    MovementSpeed: 0.3
    FollowRange: 32
    AlwaysShowName: true
  Drops: []
  # The carrier stays at normal size and the model is drawn as authored (the throne floats half a block up, the ring's
  # top 8.9 blocks); its ob_hitbox bone covers him and the throne's seat and back, never the ring. idle, walk, spawn and
  # death play by themselves; the rest come from Archevoker.java (Skills/Archevoker.yml).
  Skills:
  - model{m=occultech_archevoker} @self ~onSpawn
  - bodyrotation{mh=30;mnh=-30;rde=0;rdu=3} @self ~onSpawn
  - skill{s=ARCHEVOKER_DEATH} @self ~onDeath

# His two casting hands, his totems: killable, evasive. Archevoker.java flies them (the carrier's own mind is off) and
# decides when they draw, dodge and die; a dead hand's model plays its death clip on a stand-in with the eyelid shut.
OCCULTECH_ARCHEVOKER_HAND_CYAN:
  Type: VEX
  Display: '&bGilded Hand'
  Health: 110
  Damage: 0
  Armor: 0
  Options:
    Despawn: true
    PreventOtherDrops: true
    PreventMobKillDrops: true
    PreventItemPickup: true
    KnockbackResistance: 1
    AlwaysShowName: false
  Drops: []
  Skills:
  - model{m=occultech_archevoker_hand_cyan} @self ~onSpawn

OCCULTECH_ARCHEVOKER_HAND_PURPLE:
  Type: VEX
  Display: '&dGilded Hand'
  Health: 110
  Damage: 0
  Armor: 0
  Options:
    Despawn: true
    PreventOtherDrops: true
    PreventMobKillDrops: true
    PreventItemPickup: true
    KnockbackResistance: 1
    AlwaysShowName: false
  Drops: []
  Skills:
  - model{m=occultech_archevoker_hand_purple} @self ~onSpawn
"""


def main():
    SKILLS.write_text(skills(), encoding="utf-8")
    MOBS.write_text(MOB, encoding="utf-8")
    print("wrote", SKILLS.relative_to(ROOT), "and", MOBS.relative_to(ROOT))


if __name__ == "__main__":
    main()
