"""The Night Matriarch, session 8: writes her cosmetic Mythic skills (src/main/mythic/Skills/NightMatriarch.yml).

Look and sound only: NightMatriarch.java decides when each skill runs and deals every hit. The sculk's glow states
(session 6) are BetterModel tints on her glow bones - the eye, the sensor tufts and the six warden horns - each
re-applied 12 ticks later, after any hit flash (BetterModel restores a bone's previous tint when a flash ends).

Run from the repository root: python tools/art/bosses/matriarch_mythic_skills.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "src/main/mythic/Skills/NightMatriarch.yml"
M = "occultech_night_matriarch"
BONES = ["glow_eye", "glow_tendrils"] + [f"glow_gill_{s}_{i}" for s in ("left", "right") for i in range(3)]
TINTS = {"DAY": "768690", "NIGHT": "FFFFFF", "TELL": "FFFFFF", "GROUNDED": "4E5A62", "DEAD": "22262A"}


def glow(colour):
    return [f"  - tint{{m={M};p={bone};c={colour}}} @self" for bone in BONES]


def skills():
    out = ["# Look and sound only. NightMatriarch.java decides when each of these runs and deals every hit.",
           "# Generated by tools/art/bosses/matriarch_mythic_skills.py.",
           "# The sculk's glow is a BetterModel tint on her glow bones: day 768690 (dimmed), night FFFFFF (the full glow),",
           "# the dive's tell FFFFFF, grounded 4E5A62 (guttering), dead 22262A. Each is applied again 12 ticks later.", ""]
    for state in ("DAY", "NIGHT", "GROUNDED"):
        out += [f"NIGHT_MATRIARCH_STATE_{state}:", "  Skills:"] + glow(TINTS[state]) + ["  - delay 12"] + glow(TINTS[state])
    out += ["NIGHT_MATRIARCH_TELL:", "  Skills:", f"  - state{{m={M};s=tell}} @self"] + glow(TINTS["TELL"])
    out += ["  - sound{s=entity.phantom.swoop;v=2;p=0.5} @self", "  - sound{s=block.sculk_shrieker.shriek;v=1.4;p=0.8} @self",
            "  - particles{p=sculk_soul;a=24;hs=1.6;vs=0.6;s=0.04;y=1.0} @self", "  - delay 12"] + glow(TINTS["TELL"])
    out += ["NIGHT_MATRIARCH_DIVE:", "  Skills:", f"  - state{{m={M};s=dive}} @self",
            "  - sound{s=entity.phantom.flap;v=2;p=0.5} @self",
            "NIGHT_MATRIARCH_IMPACT:", "  Skills:", f"  - state{{m={M};s=impact}} @self"] + glow(TINTS["GROUNDED"])
    out += ["  - sound{s=block.sculk.break;v=2;p=0.5} @self", "  - particles{p=sculk_charge_pop;a=40;hs=2.5;vs=0.4;s=0.06;y=0.4} @self",
            "  - particles{p=sculk_soul;a=16;hs=2;vs=0.4;s=0.04;y=0.6} @self", "  - delay 12"] + glow(TINTS["GROUNDED"])
    out += ["NIGHT_MATRIARCH_TAKEOFF:", "  Skills:", f"  - state{{m={M};s=takeoff}} @self",
            "  - sound{s=entity.phantom.flap;v=2;p=0.6} @self",
            "NIGHT_MATRIARCH_CALL:", "  Skills:", f"  - state{{m={M};s=call}} @self",
            "  - sound{s=entity.phantom.ambient;v=2.5;p=0.4} @self", "  - sound{s=block.sculk_shrieker.shriek;v=1.6;p=0.6} @self",
            "  - particles{p=sculk_soul;a=30;hs=2;vs=1;s=0.05;y=1.2} @self",
            "NIGHT_MATRIARCH_BITE:", "  Skills:", f"  - state{{m={M};s=bite}} @self", "  - delay 6",
            "  - sound{s=entity.phantom.bite;v=1.6;p=0.6} @self",
            "NIGHT_MATRIARCH_FLINCH:", "  Skills:", f"  - state{{m={M};s=flinch}} @self",
            "NIGHT_MATRIARCH_DEATH:", "  Skills:", f"  - state{{m={M};s=death}} @self"] + glow(TINTS["DEAD"])
    out += ["  - sound{s=entity.phantom.death;v=2;p=0.5} @self", "  - particles{p=sculk_soul;a=40;hs=2;vs=1;s=0.04;y=1.0} @self", ""]
    return "\n".join(out)


if __name__ == "__main__":
    OUT.write_text(skills(), encoding="utf-8")
    print(OUT)
