def main():
    print(json.dumps(ship(), indent=1))
    SKILLS.write_text(skills(), encoding="utf-8")
    MOBS.write_text(MOB, encoding="utf-8")
    print("seat", SEAT.tolist(), "offset", OFFSET.tolist(), "hand (up, ahead, right)", hand_at_release())


if __name__ == "__main__":
    main()
