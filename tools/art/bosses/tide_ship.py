"""The Tidebreaker, session 8: ship both models and write their Mythic mobs and cosmetic skills.

- src/main/models/occultech_tidebreaker.bbmodel (the Viking, worn by the drowned) and occultech_tidebreaker_mount.bbmodel
  (the nautilus and longship, worn by an invisible pig).
- The drowned rides the nautilus at the vanilla seat, so the Viking's model is moved from there to the deck. SEAT is that
  seat, measured in game, in model units from the nautilus's feet.
- The mount loses its hitbox: the nautilus can't be hurt and it must not catch the swings aimed at the rider.
- src/main/mythic/Mobs/Tidebreaker.yml and Skills/Tidebreaker.yml: look and sound only. Tidebreaker.java decides when each
  runs and deals every hit.
- Refuses to ship with faces that would flicker, or with half-clear texels.

Run from the repository root (through tide_s7.py), with a folder holding the 26.2 zombie textures as the last argument:
python tools/art/bosses/tide_ship.py <folder>
"""
import base64
import io
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "tools" / "art"))
from bosskit.checks import flicker_pairs  # noqa: E402
from bosses import tide_s2 as s2, tide_s3 as s3, tide_s7 as s7  # noqa: E402

S7 = ROOT / "docs/art/bosses/tidebreaker/overhaul/s7_animation"
MODELS = ROOT / "src/main/models"
SKILLS = ROOT / "src/main/mythic/Skills/Tidebreaker.yml"
MOBS = ROOT / "src/main/mythic/Mobs/Tidebreaker.yml"
RIDER, MOUNT = "occultech_tidebreaker", "occultech_tidebreaker_mount"
SEAT = np.array((0.0, float(sys.argv[-2]) if len(sys.argv) > 2 else 16.0, 0.0))   # the vanilla seat (see the docstring)
OFFSET = np.array(s2.FEET) - SEAT
STATES = {"CALM": "FFD66E", "RAM": "78BEFF", "WINDED": "96683A"}
DEAD = "2C2A2E"


def check(kind, rig, name):
    clash = flicker_pairs(s3.build(kind, "idle").cubes)
    if clash:
        raise SystemExit(f"{name}: faces that would flicker in game: {clash[:5]}")
    for tex in rig["textures"]:
        a = np.array(Image.open(io.BytesIO(base64.b64decode(tex["source"].split(",", 1)[1]))).convert("RGBA"))[..., 3]
        half = int(((a > 0) & (a < 255)).sum())
        if half:
            raise SystemExit(f"{name}: {half} half-clear texels")


def shift(rig, d):
    """Moves a finished model: cubes and bones (the clips are relative to them)."""
    for e in rig["elements"]:
        for k in ("from", "to", "origin"):
            e[k] = [round(v + float(d[i]), 4) for i, v in enumerate(e[k])]

    def walk(nodes):
        for n in nodes:
            if isinstance(n, dict):
                n["origin"] = [round(v + float(d[i]), 4) for i, v in enumerate(n["origin"])]
                walk(n.get("children", []))

    for g in rig["groups"]:
        g["origin"] = [round(v + float(d[i]), 4) for i, v in enumerate(g["origin"])]
    walk(rig["outliner"])


def drop_hitbox(rig):
    uuids = [n["children"][0] for n in rig["outliner"] if isinstance(n, dict) and n.get("name") == "ob_hitbox"]
    rig["outliner"] = [n for n in rig["outliner"] if not (isinstance(n, dict) and n.get("name") == "ob_hitbox")]
    rig["groups"] = [g for g in rig["groups"] if g["name"] != "ob_hitbox"]
    rig["elements"] = [e for e in rig["elements"] if e["uuid"] not in uuids]


def ship():
    out = {}
    for kind, src, name in (("mount", s3.MOUNT_ID, MOUNT), ("rider", s3.RIDER_ID, RIDER)):
        rig = json.loads((S7 / f"{src}.bbmodel").read_text(encoding="utf-8"))
        check(kind, rig, name)
        if kind == "mount":
            drop_hitbox(rig)
        else:
            shift(rig, OFFSET)
        rig["name"] = name
        for tex in rig["textures"]:
            tex["name"] = f"{name}.png"
        (MODELS / f"{name}.bbmodel").write_text(json.dumps(rig, indent=1) + "\n", encoding="utf-8")
        out[name] = {"animations": sorted(a["name"] for a in rig["animations"]), "elements": len(rig["elements"])}
    return out


def hand_at_release():
    """Where his hand is when the volley leaves it, in blocks from the carrier: (up, ahead, right)."""
    sp = next(s for t, s in s7.clips()["throw"][2] if t == 0.7)
    m = s7.fresh("rider")
    s2.pose_rider(m, sp)
    g = s2.group(m, "hand_right")
    p = (g.world_matrix() @ np.array((*g.origin, 1.0)))[:3] + OFFSET
    return round(float(p[1]) / 16, 2), round(float(-p[2]) / 16, 2), round(float(p[0]) / 16, 2)


def skill(name, lines):
    return [f"{name}:", "  Skills:"] + lines + [""]


def skills():
    out = ["# Look and sound only. Tidebreaker.java decides when each of these runs and deals every hit.",
           "# Generated by tools/art/bosses/tide_ship.py. The rider's skills are TIDEBREAKER_*, the mount's TIDEBREAKER_MOUNT_*.",
           "# The lantern (glow_lantern) is painted neutral and tinted: calm FFD66E, ram 78BEFF (the warning lane's blue),",
           "# winded 96683A (guttering), dead 2C2A2E.", ""]
    for clip, sound in (("RAM_TELL", "entity.drowned.ambient;v=2;p=0.6"), ("RAM", ""), ("WINDED", "entity.drowned.hurt;v=1.6;p=0.5")):
        lines = [f"  - state{{m={RIDER};s={clip.lower()}}} @self"]
        if sound:
            lines.append(f"  - sound{{s={sound}}} @self")
        out += skill(f"TIDEBREAKER_{clip}", lines)
        out += skill(f"TIDEBREAKER_MOUNT_{clip}", [f"  - state{{m={MOUNT};s={clip.lower()}}} @self"])
    for clip in ("THROW", "THRUST", "FLINCH"):
        out += skill(f"TIDEBREAKER_{clip}", [f"  - state{{m={RIDER};s={clip.lower()}}} @self"])
    for name, colour in STATES.items():
        out += skill(f"TIDEBREAKER_MOUNT_STATE_{name}", [f"  - tint{{m={MOUNT};p=glow_lantern;c={colour}}} @self"])
    out += skill("TIDEBREAKER_DEATH", ["  - sound{s=entity.drowned.death;v=2;p=0.6} @self"])
    out += skill("TIDEBREAKER_MOUNT_DEATH", [f"  - tint{{m={MOUNT};p=glow_lantern;c={DEAD}}} @self"])
    return "\n".join(out)


