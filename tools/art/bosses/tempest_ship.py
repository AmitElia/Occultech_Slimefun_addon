"""Tempest, session 8: ship the model and write its Mythic mob and cosmetic skills.

- src/main/models/occultech_tempest.bbmodel: the final rig (session 7: the painted model with its hitbox, glow bones and
  every clip), carrying the **neutral** heart and glyphs (session 6): the fight tints them per state.
- src/main/mythic/Mobs/Tempest.yml and Skills/Tempest.yml: look and sound only. Tempest.java decides when each runs and
  deals every hit.
- The carrier is an invisible BLAZE, never a breeze: a breeze's wind and eyes layers draw even when it is invisible
  (LivingEntityRenderer runs every layer; neither breeze layer checks invisibility, 26.2 client).
- Refuses to ship with faces that would flicker, or with half-clear texels.

Run from the repository root after tempest_s7.py, with the folder holding assets/ from the 26.2 client as the last
argument: python tools/art/bosses/tempest_ship.py <folder>
"""
import base64
import io
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "tools" / "art"))
from bosskit.checks import flicker_pairs  # noqa: E402

S7 = ROOT / "docs/art/bosses/tempest/overhaul/s7_animation"
MODELS = ROOT / "src/main/models"
SKILLS = ROOT / "src/main/mythic/Skills/Tempest.yml"
MOBS = ROOT / "src/main/mythic/Mobs/Tempest.yml"
NAME = "occultech_tempest"
GLOWS = ["glow_heart", "glow_circlet"] + [f"glow_shard{i}" for i in range(7)]
STATES = {"CALM": "56E8D0", "TELL": "D6FFF6", "STORM": "8CB0FF", "SPENT": "285450"}   # session 6
EYES = {"SPENT": "82828C"}
DEAD = "2C2828"


def check(rig):
    from bosses import tempest_s3 as s3
    clash = flicker_pairs(s3.build("idle").cubes)
    if clash:
        raise SystemExit(f"faces that would flicker in game: {clash[:5]}")
    for tex in rig["textures"]:
        a = np.array(Image.open(io.BytesIO(base64.b64decode(tex["source"].split(",", 1)[1]))).convert("RGBA"))[..., 3]
        if ((a > 0) & (a < 255)).any():
            raise SystemExit("half-clear texels")


def ship():
    rig = json.loads((S7 / f"{NAME}_rig.bbmodel").read_text(encoding="utf-8"))
    check(rig)
    rig["name"] = NAME
    for tex in rig["textures"]:
        tex["name"] = f"{NAME}.png"
    (MODELS / f"{NAME}.bbmodel").write_text(json.dumps(rig, indent=1) + "\n", encoding="utf-8")
    return {"animations": sorted(a["name"] for a in rig["animations"]), "elements": len(rig["elements"])}


def tints(colour, bones=GLOWS):
    return [f"  - tint{{m={NAME};p={bone};c={colour}}} @self" for bone in bones]


def skill(name, lines):
    return [f"{name}:", "  Skills:"] + lines + [""]


def skills():
    out = ["# Look and sound only. Tempest.java decides when each of these runs and deals every hit.",
           "# Generated by tools/art/bosses/tempest_ship.py. The heart and glyphs are painted neutral and tinted per state",
           "# (session 6): calm, tell (a wind-up), storm (below half), spent (the opening), dead. The breeze's eyes keep",
           "# vanilla's colours (tint FFFFFF) except when spent or dead.", ""]
    out += skill("TEMPEST_VOLLEY", [f"  - state{{m={NAME};s=volley}} @self", "  - sound{s=entity.breeze.inhale;v=2;p=0.6} @self"]
                 + tints(STATES["TELL"]))
    out += skill("TEMPEST_BURST", [f"  - state{{m={NAME};s=burst}} @self"] + tints(STATES["TELL"]))
    out += skill("TEMPEST_SPENT", [f"  - state{{m={NAME};s=spent}} @self", "  - sound{s=entity.breeze.slide;v=2;p=0.5} @self"]
                 + tints(STATES["SPENT"]) + tints(EYES["SPENT"], ["glow_eyes"]))
    out += skill("TEMPEST_RECOVER", [f"  - state{{m={NAME};s=recover}} @self", "  - sound{s=entity.breeze.jump;v=2;p=0.6} @self"]
                 + tints("FFFFFF", ["glow_eyes"]))
    out += skill("TEMPEST_SQUALL", [f"  - defaultstate{{m={NAME};t=idle;s=squall}} @self"])
    out += skill("TEMPEST_SQUALL_END", [f"  - defaultstate{{m={NAME};t=idle;s=idle}} @self"])
    out += skill("TEMPEST_SPLIT", [f"  - state{{m={NAME};s=split}} @self", "  - sound{s=entity.breeze.wind_burst;v=2;p=0.5} @self",
                                   "  - delay 20", "  - sound{s=block.trial_spawner.break;v=2;p=0.6} @self"]
                 + tints(STATES["STORM"]))
    out += skill("TEMPEST_FLINCH", [f"  - state{{m={NAME};s=flinch}} @self"])
    for state, colour in STATES.items():
        out += skill(f"TEMPEST_STATE_{state}", tints(colour) + tints(EYES.get(state, "FFFFFF"), ["glow_eyes"]))
    out += skill("TEMPEST_DEATH", ["  - sound{s=entity.breeze.death;v=2;p=0.6} @self"] + tints(DEAD) + tints(DEAD, ["glow_eyes"]))
    return "\n".join(out)


def mobs():
    return "\n".join([
        "# Tempest's body: the Shattered Seal model on an invisible blaze (a breeze would still draw its wind and eyes).",
        "# Occultech steers it, decides every volley, burst and squall, deals all damage (Tempest.java) and hands out loot.",
        "# Health is the solo value; Occultech multiplies it for the group after the spawn.", "",
        "OCCULTECH_TEMPEST:", "  Type: BLAZE", "  Display: '&bTempest'", "  Health: 300", "  Damage: 0", "  Armor: 0",
        "  Options:", "    # Occultech rebuilds the fight from its saved state; Mythic never restores it", "    Despawn: true",
        "    PreventOtherDrops: true", "    PreventMobKillDrops: true", "    PreventItemPickup: true", "    KnockbackResistance: 1",
        "    FollowRange: 40", "    Silent: true", "    AlwaysShowName: true", "  Drops: []", "  Skills:",
        f"  - model{{m={NAME}}} @self ~onSpawn", f"  - state{{m={NAME};s=spawn}} @self ~onSpawn",
        "  - bodyrotation{mh=40;mnh=-40;rde=0;rdu=3} @self ~onSpawn", "  - skill{s=TEMPEST_STATE_CALM} @self ~onSpawn",
        "  - skill{s=TEMPEST_DEATH} @self ~onDeath", ""])


def main():
    print(json.dumps(ship(), indent=1))
    SKILLS.write_text(skills(), encoding="utf-8")
    MOBS.write_text(mobs(), encoding="utf-8")


if __name__ == "__main__":
    main()
