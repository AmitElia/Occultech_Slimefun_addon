"""Witch Coven effects, E3: writes the coven's cosmetic Mythic skills (src/main/mythic/Skills/WitchCoven.yml).

Look and sound only, like Volley's and Brood Mother's: WitchCoven.java decides when each skill runs, which witch has
which role, and deals every heal, curse and hit. One model per sister; the skills are named after her vessel. Each
action's particles and sounds land on session 7's release times (heal 16 ticks in, curse 20, throw 13, the role
strike 12). Role colours are BetterModel tints over the neutral brew (session 6), re-applied 12 ticks after each
swap, after any hit flash (BetterModel restores a bone's previous tint when a flash ends).

Run from the repository root: python tools/art/bosses/coven_mythic_skills.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "src/main/mythic/Skills/WitchCoven.yml"
VESSELS = {"cauldron": "occultech_witch_coven_cauldron", "bottles": "occultech_witch_coven_bottles",
           "pot": "occultech_witch_coven_pot"}
# the server starts each clip this many ticks before its moment (WitchCoven.java: ROTATE_LEAD, HEAL_LEAD, THROW_LEAD)
ROTATE, HEAL, THROW = 10, 15, 15
ROLES = {"HEALER": "96D66C", "CURSER": "B07CD4", "BOMBER": "DC7058", "SPENT": "606064"}
GREEN, PURPLE, RED = "#96d66c", "#b07cd4", "#dc7058"


def tint_parts(vessel):
    return ["glow_brew"] + (["glow_brew_held"] if vessel == "bottles" else []) + (["glow_cast"] if vessel == "cauldron" else [])


def tints(m, vessel, colour):
    return [f"  - tint{{m={m};p={p};c={colour}}} @self" for p in tint_parts(vessel)]


def skills():
    out = ["# Look and sound only. WitchCoven.java decides when each of these runs, which witch has which role, every heal,",
           "# curse mark and thrown potion, and every hit. One model per sister; the skills are named after her vessel.",
           "# Generated by tools/art/bosses/coven_mythic_skills.py.",
           "# Role colours are BetterModel tints over the neutral brew: healer 96D66C, curser B07CD4, bomber DC7058, and",
           "# spent 606064 for a dead sister. The burst sprites (bubble, droplets, shards), the throwables riding the potions,",
           "# the floor marks, the swap ripple, the ambient bubbles in the role colour and the death spill are drawn by the",
           "# plugin (AirEffects, FloorDecals), which knows the roles and the potions.", ""]
    for v, m in VESSELS.items():
        V = "WITCH_COVEN_" + v.upper()
        out += [f"# ---- the {v} witch",
                f"{V}_SPAWN:", "  Skills:", f"  - state{{m={m};s=spawn}} @self",
                "  - particles{p=witch;a=30;hs=0.6;vs=0.2;s=0.05;y=0.2} @self",
                "  - sound{s=entity.witch.ambient;v=1.4;p=0.6} @self"]
        for role, col in ROLES.items():
            if role == "SPENT":
                out += [f"{V}_BECOMES_SPENT:", "  Skills:"] + tints(m, v, col)
                continue
            # at once: her spawn, a fight resumed, the roles reshuffled after a death
            out += [f"{V}_IS_{role}:", "  Skills:"] + tints(m, v, col)
            # the rotation: the clip starts ROTATE ticks before the roles change; the brew changes colour on the
            # strike, and again 12 ticks later, after any hit flash (BetterModel restores a bone's previous tint)
            out += [f"{V}_BECOMES_{role}:", "  Skills:", f"  - state{{m={m};s=rotation}} @self", f"  - delay {ROTATE}"]
            out += tints(m, v, col)
            out += [f"  - particles{{p=dust;color=#{col.lower()};size=1.2;a=14;hs=0.5;vs=0.4;y=2.2}} @self",
                    "  - sound{s=block.brewing_stand.brew;v=1.2;p=1.2} @self", "  - delay 12"] + tints(m, v, col)
        # heal: the release is 0.8 s (16 ticks) in; @trigger is the sister she heals
        out += [f"{V}_HEAL:", "  Skills:", f"  - state{{m={m};s=heal}} @self", f"  - delay {HEAL}",
                f"  - effect:particleline{{p=dust;color={GREEN};size=1.3;a=1;db=0.35;fo=false;yo=2.0;tyo=1.8}} @trigger",
                f"  - particles{{p=dust;color={GREEN};size=1;a=24;hs=0.5;vs=0.9;y=1.4;s=0}} @trigger",
                "  - particles{p=happy_villager;a=8;hs=0.5;vs=0.8;y=1.6} @trigger",
                "  - sound{s=entity.witch.drink;v=1;p=1.3} @trigger"]
        if v == "bottles":
            out += ["  - sound{s=block.glass.break;v=0.8;p=1.4} @trigger"]
        if v == "pot":
            out += ["  - particles{p=falling_dust;bd=green_concrete_powder;a=10;hs=0.3;vs=0.2;y=1.8} @self"]
        # curse: the clip starts with the 20-tick floor warning; @trigger is the marked player
        out += [f"{V}_CURSE:", "  Skills:", f"  - state{{m={m};s=curse}} @self",
                "  - sound{s=entity.evoker.prepare_attack;v=1;p=1.4} @self",
                "  - particles{p=witch;a=20;hs=0.5;vs=0.1;y=0.1;repeat=4;ri=5} @trigger"]
        if v == "cauldron":
            out += [f"  - particles{{p=dust;color={PURPLE};size=1.4;a=6;hs=0.4;vs=0.3;y=2.4;repeat=4;ri=5}} @self"]
        out += ["  - delay 20",
                f"  - particles{{p=dust;color={PURPLE};size=1.6;a=40;hs=0.7;vs=0.1;y=0.1;s=0}} @trigger",
                "  - particles{p=large_smoke;a=8;hs=0.5;vs=0.1;y=0.2;s=0.02} @trigger",
                "  - sound{s=entity.illusioner.cast_spell;v=1;p=0.8} @trigger"]
        # throw: the release is 0.65 s (13 ticks) in; the plugin launches the potion then and rides the throwable on it
        out += [f"{V}_THROW:", "  Skills:", f"  - state{{m={m};s=throw}} @self", f"  - delay {THROW}",
                "  - sound{s=entity.witch.throw;v=1.2;p=0.9} @self",
                f"  - particles{{p=dust;color={RED};size=1;a=8;hs=0.3;vs=0.3;y=2.4}} @self"]
        out += [f"{V}_FLINCH:", "  Skills:", f"  - state{{m={m};s=flinch}} @self",
                f"{V}_CACKLE:", "  Skills:", f"  - state{{m={m};s=cackle}} @self",
                "  - sound{s=entity.witch.celebrate;v=1.4;p=0.8} @self",
                f"{V}_GLANCE:", "  Skills:", f"  - state{{m={m};s=glance}} @self",
                "  - sound{s=entity.witch.ambient;v=1;p=0.6} @self",
                f"{V}_DEATH:", "  Skills:", f"  - state{{m={m};s=death}} @self"] + tints(m, v, "606064")
        out += ["  - sound{s=entity.witch.death;v=1.2;p=0.8} @self",
                "  - particles{p=large_smoke;a=16;hs=0.5;vs=0.6;y=1.6;s=0.02} @self",
                f"{V}_HOVER:", "  Skills:",                       # a few motes of dust under the hem, on a timer
                "  - particles{p=ash;a=3;hs=0.4;vs=0.05;y=0.3} @self", ""]
    return "\n".join(out)


if __name__ == "__main__":
    OUT.write_text(skills(), encoding="utf-8")
    print(OUT)
