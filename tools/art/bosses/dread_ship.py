"""Dread Riders, session 8: ship the four models and write their Mythic mobs and cosmetic skills.

- src/main/models/occultech_dread_riders_<vanguard|outrider>[_mount].bbmodel. The riders are the fight's two main bosses
  (BossFight.spawnBoss("VANGUARD" / "OUTRIDER")), the mounts its lookalikes ("VANGUARD_MOUNT" / "OUTRIDER_MOUNT"), so
  MythicBody finds them as OCCULTECH_DREAD_RIDERS_<PART> wearing occultech_dread_riders_<part>.
- The carriers draw nothing: invisible pigs under the horses (as under the Tidebreaker's nautilus), an invisible skeleton
  and zombie with empty hands. Each rider rides its pig at the vanilla seat, PIG_SEAT model units above the pig's feet
  (the Tidebreaker's drowned measured 2.7 in game), so the rider's model is moved from there to the saddle.
- The mounts have no hitbox: they can't be hurt and must not catch swings meant for the riders. The riders' hitboxes
  run from the ground to the helm, so a swing at the horse's body reaches its rider.
- src/main/mythic/Mobs/DreadRiders.yml and Skills/DreadRiders.yml: look and sound only. DreadRiders.java decides when each
  runs and deals every hit.
- Refuses to ship with half-clear texels.

Run from the repository root, after dread_s7.py: python tools/art/bosses/dread_ship.py
"""
import base64
import io
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "tools" / "art"))
from bosses import dread_concepts as dc, dread_s2 as s2, dread_s3 as s3, dread_s6 as s6  # noqa: E402

S7 = ROOT / "docs/art/bosses/dread_riders/overhaul/s7_animation"
MODELS = ROOT / "src/main/models"
SKILLS = ROOT / "src/main/mythic/Skills/DreadRiders.yml"
MOBS = ROOT / "src/main/mythic/Mobs/DreadRiders.yml"
PIG_SEAT = 2.7
GLOWS = {"VANGUARD": ["glow_lance"], "VANGUARD_MOUNT": ["glow_eyes", "glow_sigil", "glow_banner"],
         "OUTRIDER": ["glow_arrow", "glow_rune"], "OUTRIDER_MOUNT": ["glow_eyes"]}


def hexc(rgb):
    return "".join(f"{v:02X}" for v in rgb)


def check(rig, name):
    for tex in rig["textures"]:
        a = np.array(Image.open(io.BytesIO(base64.b64decode(tex["source"].split(",", 1)[1]))).convert("RGBA"))[..., 3]
        half = int(((a > 0) & (a < 255)).sum())
        if half:
            raise SystemExit(f"{name}: {half} half-clear texels")


def shift(rig, d):
    for e in rig["elements"]:
        for k in ("from", "to", "origin"):
            e[k] = [round(v + float(d[i]), 4) for i, v in enumerate(e[k])]

    def walk(nodes):
        for n in nodes:
            if isinstance(n, dict):
                n["origin"] = [round(v + float(d[i]), 4) for i, v in enumerate(n["origin"])]
                walk(n.get("children", []))

    for g in rig["groups"]:
        g["origin"] = [round(v + float(d[i]), 4) for i, v in enumerate(g["origin"])]
    walk(rig["outliner"])


def seat(kind):
    return np.array(dc.frame(s2.HORSE[kind], s2.REST)["seat"]) * s3.SCALE


def ship():
    out = {}
    for kind in ("vanguard", "outrider"):
        for part, src in (("mount", f"occultech_dread_{kind}_mount_rig"), ("rider", f"occultech_dread_{kind}_rig")):
            name = f"occultech_dread_riders_{kind}" + ("_mount" if part == "mount" else "")
            rig = json.loads((S7 / f"{src}.bbmodel").read_text(encoding="utf-8"))
            check(rig, name)
            if part == "rider":
                d = seat(kind) - np.array([0, PIG_SEAT, 0])
                shift(rig, d)
            rig["name"] = name
            for tex in rig["textures"]:
                tex["name"] = f"{name}.png"
            (MODELS / f"{name}.bbmodel").write_text(json.dumps(rig, separators=(",", ":")) + "\n", encoding="utf-8")
            out[name] = {"animations": sorted(a["name"] for a in rig["animations"]), "elements": len(rig["elements"])}
    return out


def skill(name, lines):
    return [f"DREAD_RIDERS_{name}:", "  Skills:"] + lines + [""]


def model_of(part):
    return "occultech_dread_riders_" + part.lower()


def tint_lines(part, colour):
    return [f"  - tint{{m={model_of(part)};p={p};c={hexc(colour)}}} @self" for p in GLOWS[part]]


def skills():
    out = ["# Look and sound only. DreadRiders.java decides when each of these runs and deals every hit.",
           "# Generated by tools/art/bosses/dread_ship.py. Skills are DREAD_RIDERS_<PART>_<ACTION>; the parts are",
           "# VANGUARD, VANGUARD_MOUNT, OUTRIDER, OUTRIDER_MOUNT. The glows are painted neutral and tinted per state;",
           "# the survivor of a fallen pair takes the fallen rider's colour (the enrage).", ""]
    sounds = {"VANGUARD_REAR": "entity.zombie_horse.angry;v=2;p=0.6", "VANGUARD_CHARGE": "entity.horse.gallop;v=2;p=0.6",
              "VANGUARD_STUNNED": "entity.zombie_horse.hurt;v=2;p=0.6", "OUTRIDER_MOUNT_HALT": "entity.skeleton_horse.ambient;v=1.5;p=0.7",
              "VANGUARD_SWEEP": "entity.player.attack.sweep;v=1.5;p=0.6", "VANGUARD_THROW": "item.trident.throw;v=1.5;p=0.7",
              "OUTRIDER_DRAW": "item.crossbow.loading_middle;v=1.5;p=0.6", "OUTRIDER_RAIN": "item.crossbow.loading_end;v=2;p=0.6"}
    clips = {"VANGUARD": ["REAR", "CHARGE", "STUNNED", "SWEEP", "THROW", "FLINCH", "SPAWN"],
             "VANGUARD_MOUNT": ["REAR", "CHARGE", "STUNNED", "FLINCH", "SPAWN"],
             "OUTRIDER": ["HALT", "DRAW", "SNIPE", "VOLLEY", "RAIN", "FLINCH", "SPAWN"],
             "OUTRIDER_MOUNT": ["HALT", "FLINCH", "SPAWN"]}
    arrow = {"DRAW": 40, "SNIPE": 31, "VOLLEY": 8, "RAIN": 10}       # ticks the nocked arrow shows before the loose
    for part, names in clips.items():
        for c in names:
            lines = []
            if part == "OUTRIDER" and c in arrow:
                lines.append(f"  - partvisibility{{m={model_of(part)};p=arrow;v=true}} @self")
            lines.append(f"  - state{{m={model_of(part)};s={c.lower()}}} @self")
            if f"{part}_{c}" in sounds:
                lines.append(f"  - sound{{s={sounds[part + '_' + c]}}} @self")
            if part == "OUTRIDER_MOUNT" and c == "HALT":         # the halt runs into the pawing stance of the aimed shot
                lines += ["  - delay 14", f"  - state{{m={model_of(part)};s=draw}} @self"]
            if part == "OUTRIDER" and c in arrow:
                lines += [f"  - delay {arrow[c]}", f"  - partvisibility{{m={model_of(part)};p=arrow;v=false}} @self"]
            out += skill(f"{part}_{c}", lines)
    for kind in ("VANGUARD", "OUTRIDER"):
        for state, colour in s6.STATES[kind.lower()].items():
            for part in (kind, kind + "_MOUNT"):
                out += skill(f"{part}_STATE_{state.upper()}", tint_lines(part, colour))
    return "\n".join(out)


def mob(part, kind_type, display, health, comment):
    m = model_of(part)
    lines = [f"# {comment}", f"OCCULTECH_DREAD_RIDERS_{part}:", f"  Type: {kind_type}", f"  Display: '{display}'",
             f"  Health: {health}", "  Damage: 0", "  Armor: 0", "  Options:", "    Despawn: true",
             "    PreventOtherDrops: true", "    PreventMobKillDrops: true", "    PreventItemPickup: true",
             "    PreventSunburn: true", "    KnockbackResistance: 1", "    FollowRange: 32", "    Silent: true",
             f"    AlwaysShowName: {'false' if part.endswith('MOUNT') else 'true'}", "  Drops: []", "  Skills:",
             f"  - model{{m={m}}} @self ~onSpawn",
             f"  - defaultstate{{m={m};t=walk;s=gallop}} @self ~onSpawn",
             f"  - skill{{s=DREAD_RIDERS_{part}_STATE_CALM}} @self ~onSpawn", ""]
    if not part.endswith("MOUNT"):
        lines.insert(-1, "  - bodyrotation{mh=55;mnh=-55;rde=0;rdu=3} @self ~onSpawn")
    return lines


def mobs():
    out = ["# The Dread Riders' four bodies. Occultech decides every ride and every attack, deals all damage",
           "# (DreadRiders.java) and hands out loot. Health is the solo value; Occultech scales it for the group after the spawn.",
           "# Generated by tools/art/bosses/dread_ship.py.", ""]
    out += mob("VANGUARD", "ZOMBIE", "&4The Vanguard", 260,
               "The Vanguard: a zombie lancer in netherite-dark plate under a horned armet. Hittable from its horse up.")
    out += mob("OUTRIDER", "SKELETON", "&bThe Outrider", 200,
               "The Outrider: a skeleton horse archer under a steppe helm, storm in its arrows. Hittable from its horse up.")
    out += mob("VANGUARD_MOUNT", "PIG", "&4Dread Charger", 100,
               "The spiked zombie charger's carrier: an invisible pig, which draws nothing. Invulnerable; it rides where the fight sends it.")
    out += mob("OUTRIDER_MOUNT", "PIG", "&bBone Courser", 100,
               "The skeleton courser's carrier: an invisible pig. Invulnerable.")
    return "\n".join(out)


def main():
    print(json.dumps(ship(), indent=1))
    SKILLS.write_text(skills(), encoding="utf-8")
    MOBS.write_text(mobs(), encoding="utf-8")
    for kind in ("vanguard", "outrider"):
        print(kind, "seat (blocks)", [round(float(v) / 16, 3) for v in seat(kind)])


if __name__ == "__main__":
    main()
