"""The Elder of Ash, session 8: writes his Mythic mob and cosmetic skills (src/main/mythic/Mobs|Skills/MireMonarch.yml).

Look and sound only: MireMonarch.java decides when each skill runs and deals every hit. The volcano's stages are
BetterModel tints over the near-white lava (session 6) on its glow bones; each is re-applied 12 ticks later, after any
hit flash (BetterModel restores a bone's previous tint when a flash ends). At 33% the cone's cap is hidden and the
blown-open top shown.

Run from the repository root: python tools/art/bosses/ash_mythic_skills.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SKILLS = ROOT / "src/main/mythic/Skills/MireMonarch.yml"
MOBS = ROOT / "src/main/mythic/Mobs/MireMonarch.yml"
M = "occultech_mire_monarch"
B = "MIRE_MONARCH"
LAVA_BONES = ("glow_lava", "glow_lava_cap", "glow_crater", "glow_crater_blown")
STAGES = {"DORMANT": "FF6822", "AWAKE": "FFA032", "BLOWN": "FFEC96"}
COIL, DEAD, EYE_DEAD = "FFFFFF", "3C2E2A", "462E22"


def tint(colour):
    return [f"  - tint{{m={M};p={bone};c={colour}}} @self" for bone in LAVA_BONES]


def top(blown):
    return [f"  - partvisibility{{m={M};p=cone_cap;v={'false' if blown else 'true'}}} @self",
            f"  - partvisibility{{m={M};p=cone_blown;v={'true' if blown else 'false'}}} @self"]


def stage(name):
    colour = STAGES[name]
    return tint(colour) + top(name == "BLOWN")


def skills():
    out = ["# Look and sound only. MireMonarch.java decides when each of these runs and deals every hit.",
           "# Generated by tools/art/bosses/ash_mythic_skills.py.",
           "# The volcano's stages are BetterModel tints over the near-white lava: dormant FF6822 (deep orange-red),",
           "# awake FFA032 (bright orange), blown FFEC96 (white-hot, the cap swapped for the blown top), the coil's flare",
           "# FFFFFF, dead 3C2E2A. The crater's smoke and flares and the pipe's smoke are drawn by the plugin.", ""]
    for name in STAGES:
        # at once: his spawn, a fight resumed, after the leap's flare
        out += [f"{B}_STAGE_{name}:", "  Skills:"] + stage(name) + ["  - delay 12"] + stage(name)
    out += [f"{B}_COIL:", "  Skills:", f"  - state{{m={M};s=coil}} @self"] + tint(COIL)
    out += ["  - sound{s=entity.frog.ambient;v=2;p=0.5} @self", "  - delay 10",
            "  - sound{s=block.lava.pop;v=1.6;p=0.6} @self", "  - delay 12"] + tint(COIL)
    out += [f"{B}_LEAP:", "  Skills:", f"  - state{{m={M};s=leap}} @self",
            "  - sound{s=entity.frog.long_jump;v=2;p=0.5} @self"]
    out += [f"{B}_LAND:", "  Skills:", f"  - state{{m={M};s=land}} @self",
            "  - sound{s=entity.ravager.stunned;v=1.6;p=0.5} @self"]
    out += [f"{B}_TONGUE:", "  Skills:", f"  - state{{m={M};s=tongue}} @self",
            "  - sound{s=entity.frog.ambient;v=1.6;p=0.6} @self", "  - delay 16",
            "  - sound{s=block.lava.ambient;v=1.4;p=0.8} @self"]
    out += [f"{B}_ERUPT:", "  Skills:", f"  - state{{m={M};s=erupt}} @self",
            "  - sound{s=entity.frog.death;v=2;p=0.4} @self", "  - delay 18"] + stage("AWAKE")
    out += ["  - delay 12"] + stage("AWAKE")
    out += [f"{B}_BLOW:", "  Skills:", f"  - state{{m={M};s=blow}} @self",
            "  - sound{s=entity.warden.heartbeat;v=2;p=0.6} @self", "  - delay 18"] + stage("BLOWN")
    out += ["  - delay 12"] + stage("BLOWN")
    out += [f"{B}_FLINCH:", "  Skills:", f"  - state{{m={M};s=flinch}} @self"]
    out += [f"{B}_DEATH:", "  Skills:", f"  - state{{m={M};s=death}} @self"] + tint(DEAD)
    out += [f"  - tint{{m={M};p=glow_eye;c={EYE_DEAD}}} @self", "  - sound{s=entity.frog.death;v=2;p=0.3} @self",
            "  - particles{p=large_smoke;a=40;hs=1.4;vs=1.2;s=0.02;y=5.5} @self", ""]
    return "\n".join(out)


MOB = """# The Elder of Ash's body: the elder toad sage with a volcano growing out of its back, on a magma cube carrier (its
# bounces flame, not slime). Occultech still decides every attack, deals all damage (MireMonarch.java) and hands out
# loot. Health is the solo value; Occultech multiplies it for the group after the spawn. The id stays MIRE_MONARCH.
OCCULTECH_MIRE_MONARCH:
  Type: MAGMA_CUBE
  Display: '&6The Elder of Ash'
  Health: 600
  Damage: 7
  Armor: 0
  Options:
    # Occultech rebuilds the body from its saved fight state; Mythic never restores it
    Despawn: true
    PreventOtherDrops: true
    PreventMobKillDrops: true
    PreventItemPickup: true
    PreventSlimeSplit: true
    MovementSpeed: 0.30
    KnockbackResistance: 0.8
    FollowRange: 32
    AlwaysShowName: true
  Drops: []
  # The carrier stays at normal size and the model is drawn as authored (9 blocks across, the crater 6.6 up); its
  # ob_hitbox bone covers his body, head, haunches and the volcano's foot and passes hits on to the carrier. idle,
  # walk, spawn and death play by themselves; the rest are his skills (Skills/MireMonarch.yml).
  Skills:
  - model{m=occultech_mire_monarch} @self ~onSpawn
  - bodyrotation{mh=30;mnh=-30;rde=0;rdu=3} @self ~onSpawn
  - skill{s=MIRE_MONARCH_DEATH} @self ~onDeath
"""


def main():
    SKILLS.write_text(skills(), encoding="utf-8")
    MOBS.write_text(MOB, encoding="utf-8")
    print("wrote", SKILLS.relative_to(ROOT), "and", MOBS.relative_to(ROOT))


if __name__ == "__main__":
    main()
