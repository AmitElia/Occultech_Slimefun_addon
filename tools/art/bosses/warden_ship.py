"""The Abyssal Warden, session 8: ship the model and write his Mythic mob and cosmetic skills.

- src/main/models/occultech_abyssal_warden.bbmodel: the Lost Helmet from session 7 (the painted atlas with the neutral
  iris, the bloodshot sclera copy, the hitbox, every clip). The Mythic carrier OCCULTECH_ABYSSAL_WARDEN wears it.
- src/main/mythic/Mobs/AbyssalWarden.yml and Skills/AbyssalWarden.yml: look and sound only. AbyssalWarden.java decides
  when each skill runs and deals every hit.
- Refuses to ship if any two faces share a plane (they flicker in game; bosskit.checks.flicker_pairs). The bloodshot
  sclera is left out of that check: it is a copy of the sclera, and the two never show together.
- Refuses to ship with half-clear texels (in game they hide whatever is drawn behind them after them).

Run from the repository root after the session scripts (through warden_s7.py): python tools/art/bosses/warden_ship.py
"""
import base64
import io
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "tools" / "art"))
from bosskit.checks import flicker_pairs  # noqa: E402
from bosses import warden_s3 as s3, warden_s6 as s6  # noqa: E402

S7 = ROOT / "docs/art/bosses/abyssal_warden/overhaul/s7_animation"
MODELS = ROOT / "src/main/models"
SKILLS = ROOT / "src/main/mythic/Skills/AbyssalWarden.yml"
MOBS = ROOT / "src/main/mythic/Mobs/AbyssalWarden.yml"
M = "occultech_abyssal_warden"
B = "ABYSSAL_WARDEN"
# the eye's states (session 6), tints over the neutral iris
STATES = {"CALM": "6EF6E2", "TRACKING": "ECFFFA", "FURIOUS": "96FFC4", "RESTING": "2C7874"}
DEAD = "1A2226"
ARM = ("arm", "forearm", "hand")
CONTACT = {"SPIKES": 20, "BURST": 16}                   # ticks into the clip: the valves blow, the window bursts


def ship():
    model = s6.rig("idle")
    cubes = [c for c in model.cubes if c.group.name != "sclera_blood"]
    clash = flicker_pairs(cubes)
    if clash:
        raise SystemExit(f"{M}: faces that would flicker in game: {clash[:5]}")
    rig = json.loads((S7 / f"{s3.MODEL_ID}.bbmodel").read_text(encoding="utf-8"))
    for tex in rig["textures"]:
        a = np.array(Image.open(io.BytesIO(base64.b64decode(tex["source"].split(",", 1)[1]))).convert("RGBA"))[..., 3]
        half = int(((a > 0) & (a < 255)).sum())
        if half:
            raise SystemExit(f"{M}: {half} half-clear texels (run warden_s5.py through warden_s7.py again)")
    rig["name"] = M
    for tex in rig["textures"]:
        tex["name"] = f"{M}.png"
    (MODELS / f"{M}.bbmodel").write_text(json.dumps(rig, indent=1) + "\n", encoding="utf-8")
    return {"animations": sorted(a["name"] for a in rig["animations"]), "elements": len(rig["elements"]),
            "hidden_bones": [g["name"] for g in rig["groups"] if not g.get("visibility", True)]}


def tint(colour, bone="glow_iris"):
    return [f"  - tint{{m={M};p={bone};c={colour}}} @self"]


def twice(lines):
    return lines + ["  - delay 12"] + lines


def show(bones, visible):
    return [f"  - partvisibility{{m={M};p={b};v={'true' if visible else 'false'}}} @self" for b in bones]


def skill(name, lines):
    return [f"{B}_{name}:", "  Skills:"] + lines


def skills(bones):
    out = ["# Look and sound only. AbyssalWarden.java decides when each of these runs and deals every hit.",
           "# Generated by tools/art/bosses/warden_ship.py.",
           "# The eye (glow_iris) is painted neutral and tinted: calm 6EF6E2 (the sea glow), tracking ECFFFA (the beam's",
           "# last second), furious 96FFC4 (below half), resting 2C7874 (the rest after the spikes), dead 1A2226.",
           "# The phase looks are part swaps: below half the bloodshot sclera; from 33% the burst window and the hand.",
           "# defaultstate replaces the idle (and from 33% the walk) so a gliding Warden never snaps the hand out", ""]
    for name, colour in STATES.items():
        out += skill(f"STATE_{name}", twice(tint(colour)))
    out += skill("UNTINT", [f"  - tint{{m={M};p={b};c=FFFFFF}} @self" for b in bones])
    # below half: the bloodshot eye, the darting idle
    furious = show(["sclera"], False) + show(["sclera_blood"], True)
    out += skill("FURIOUS", furious + [f"  - defaultstate{{m={M};t=idle;s=idle_furious}} @self"]
                 + twice(tint(STATES["FURIOUS"])) + ["  - sound{s=entity.elder_guardian.curse;v=1.6;p=0.6} @self"])
    # from 33%: the window bursts and the hand comes out; looks only, the arm swaps in at contact
    arm_out = show(["window_r_glass"], False) + show(["window_r_burst", *ARM], True)
    after = [f"  - defaultstate{{m={M};t=idle;s=idle_33}} @self", f"  - defaultstate{{m={M};t=walk;s=idle_33}} @self"]
    out += skill("BURST", [f"  - state{{m={M};s=burst}} @self",
                           "  - sound{s=entity.elder_guardian.hurt;v=2;p=0.5} @self",
                           f"  - delay {CONTACT['BURST']}"] + arm_out
                 + ["  - sound{s=block.glass.break;v=2;p=0.6} @self",
                    "  - sound{s=entity.zombie.break_wooden_door;v=1.4;p=0.6} @self",
                    "  - particles{p=splash;a=60;hs=1;vs=1;s=0.3;y=3.6} @self",
                    f"  - delay {48 - CONTACT['BURST']}"] + after)
    # a resumed fight puts the phase looks back at once, without the clips
    out += skill("PHASE_FURIOUS", furious + [f"  - defaultstate{{m={M};t=idle;s=idle_furious}} @self"])
    out += skill("PHASE_33", furious + arm_out + after)
    for clip, sound in (("BEAM", "entity.guardian.attack;v=2;p=0.5"),
                        ("LASH", "entity.guardian.hurt;v=1.6;p=0.5"),
                        ("REST", "block.bubble_column.upwards_inside;v=2;p=0.6"),
                        ("FLINCH", "")):
        for suffix in ("", "_33"):
            lines = [f"  - state{{m={M};s={clip.lower()}{suffix.lower()}}} @self"]
            if sound:
                lines.append(f"  - sound{{s={sound}}} @self")
            out += skill(clip + suffix, lines)
    for suffix in ("", "_33"):
        out += skill(f"SPIKES{suffix}", [f"  - state{{m={M};s=spikes{suffix}}} @self",
                                        "  - sound{s=entity.guardian.flop;v=2;p=0.5} @self",
                                        f"  - delay {CONTACT['SPIKES']}"] + show(["spray"], True)
                     + ["  - sound{s=block.fire.extinguish;v=2;p=0.6} @self", "  - delay 12"] + show(["spray"], False))
    out += skill("SMASH", [f"  - state{{m={M};s=smash}} @self",
                           "  - sound{s=entity.elder_guardian.ambient;v=2;p=0.5} @self",
                           "  - delay 25", "  - sound{s=entity.ravager.stunned;v=2;p=0.5} @self"])
    out += skill("DEATH", [f"  - state{{m={M};s=death}} @self"] + tint(DEAD)
                 + ["  - sound{s=entity.elder_guardian.death;v=2;p=0.6} @self"])
    return "\n".join(out) + "\n"


MOB = """# The Abyssal Warden's body: the Lost Helmet, a round copper diving-helmet bowed forward, a slit eye crammed into its
# window, flesh, tendrils and kelp growing from the open neck; from 33% a mutated hand out of the right side window.
# Occultech still decides every attack and every glide, deals all damage (AbyssalWarden.java) and hands out loot.
# Health is the solo value; Occultech multiplies it for the group after the spawn. The carrier is a guardian with its
# own mind taken away (no laser of its own, no flopping); invisible, it draws nothing.
OCCULTECH_ABYSSAL_WARDEN:
  Type: GUARDIAN
  Display: '&3Abyssal Warden'
  Health: 270
  Damage: 0
  Armor: 0
  Options:
    # Occultech rebuilds the body from its saved fight state; Mythic never restores it
    Despawn: true
    PreventOtherDrops: true
    PreventMobKillDrops: true
    PreventItemPickup: true
    KnockbackResistance: 1
    FollowRange: 32
    Silent: true
    AlwaysShowName: true
  Drops: []
  # The carrier stays at normal size and the model is drawn as authored (the hull 4.4 blocks across, the eye 3.8 up);
  # its ob_hitbox bone covers the hull and passes hits on to the carrier. idle, walk, spawn and death play by
  # themselves; the rest come from AbyssalWarden.java (Skills/AbyssalWarden.yml).
  Skills:
  - model{m=occultech_abyssal_warden} @self ~onSpawn
  - bodyrotation{mh=30;mnh=-30;rde=0;rdu=3} @self ~onSpawn
  - skill{s=ABYSSAL_WARDEN_STATE_CALM} @self ~onSpawn
  - skill{s=ABYSSAL_WARDEN_DEATH} @self ~onDeath
"""


def main():
    report = ship()
    bones = [g["name"] for g in json.loads((MODELS / f"{M}.bbmodel").read_text(encoding="utf-8"))["groups"]
             if g["name"] != "ob_hitbox"]
    SKILLS.write_text(skills(bones), encoding="utf-8")
    MOBS.write_text(MOB, encoding="utf-8")
    print(json.dumps(report, indent=1))
    print("wrote", SKILLS.relative_to(ROOT), "and", MOBS.relative_to(ROOT))


if __name__ == "__main__":
    main()
