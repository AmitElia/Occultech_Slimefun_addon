"""The Blaze Choir, session 8: ship the three singers and write their Mythic mobs and cosmetic skills.

- src/main/models/occultech_blaze_choir_<singer>.bbmodel: each singer's final rig (session 7: the painted model with its
  hitbox, glow bones and every clip), carrying the **neutral** fire (session 6): the fight tints it per state.
- src/main/mythic/Mobs/BlazeChoir.yml and Skills/BlazeChoir.yml: look and sound only. BlazeChoir.java decides when each
  runs and deals every hit.
- Refuses to ship with faces that would flicker, or with half-clear texels.

Run from the repository root after choir_s7.py: python tools/art/bosses/choir_ship.py
"""
import base64
import io
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "tools" / "art"))
from bosskit.checks import flicker_pairs  # noqa: E402

S7 = ROOT / "docs/art/bosses/blaze_choir/overhaul/s7_animation"
MODELS = ROOT / "src/main/models"
SKILLS = ROOT / "src/main/mythic/Skills/BlazeChoir.yml"
MOBS = ROOT / "src/main/mythic/Mobs/BlazeChoir.yml"
SINGERS = ("soprano", "alto", "bass")
GLOWS = {"soprano": ("glow_wisp", "glow_sail", "glow_mouth"), "alto": ("glow_ember", "glow_mouth"),
         "bass": ("glow_wisp", "glow_clapper", "glow_mouth")}
STATES = {   # session 6
    "soprano": {"CALM": "FFEEC8", "BANKED": "96684C", "HOTTER": "D6EAFF", "LAST": "B0D6FF"},
    "alto": {"CALM": "FF9E3C", "BANKED": "964A22", "HOTTER": "FFCC60", "LAST": "FFEEAA"},
    "bass": {"CALM": "EC4C28", "BANKED": "782216", "HOTTER": "FF7632", "LAST": "FFA654"},
}
DEAD = "2C2828"
STRIKE_SOUND = {"soprano": "block.note_block.chime;v=1.6;p=1.5", "alto": "block.note_block.hat;v=2;p=0.6",
                "bass": "block.bell.use;v=2;p=0.6"}
SING_SOUND = {"soprano": "block.note_block.chime;v=1.4;p=2", "alto": "block.note_block.bell;v=1.4;p=1",
              "bass": "block.bell.resonate;v=1.6;p=0.5"}


def check(rig, name):
    from bosses import choir_s3 as s3
    singer = name.rsplit("_", 1)[1]
    clash = flicker_pairs(s3.build(singer, "idle").cubes)
    if clash:
        raise SystemExit(f"{name}: faces that would flicker in game: {clash[:5]}")
    for tex in rig["textures"]:
        a = np.array(Image.open(io.BytesIO(base64.b64decode(tex["source"].split(",", 1)[1]))).convert("RGBA"))[..., 3]
        if ((a > 0) & (a < 255)).any():
            raise SystemExit(f"{name}: half-clear texels")


def ship():
    out = {}
    for singer in SINGERS:
        name = f"occultech_blaze_choir_{singer}"
        rig = json.loads((S7 / f"{name}_rig.bbmodel").read_text(encoding="utf-8"))
        check(rig, name)
        rig["name"] = name
        for tex in rig["textures"]:
            tex["name"] = f"{name}.png"
        (MODELS / f"{name}.bbmodel").write_text(json.dumps(rig, indent=1) + "\n", encoding="utf-8")
        out[name] = {"animations": sorted(a["name"] for a in rig["animations"]), "elements": len(rig["elements"])}
    return out


def skill(name, lines):
    return [f"{name}:", "  Skills:"] + lines + [""]


def tints(singer, colour):
    m = f"occultech_blaze_choir_{singer}"
    return [f"  - tint{{m={m};p={bone};c={colour}}} @self" for bone in GLOWS[singer]]


def skills():
    out = ["# Look and sound only. BlazeChoir.java decides when each of these runs and deals every hit.",
           "# Generated by tools/art/bosses/choir_ship.py. Skills are BLAZE_CHOIR_<SINGER>_<ACTION>; the fire is painted",
           "# neutral and tinted per state (session 6): calm, banked (shielded), hotter (a voice fell), last, dead.", ""]
    for singer in SINGERS:
        s, m = singer.upper(), f"occultech_blaze_choir_{singer}"
        out += skill(f"BLAZE_CHOIR_{s}_STRIKE", [f"  - state{{m={m};s=strike}} @self", "  - delay 10",
                                                 f"  - sound{{s={STRIKE_SOUND[singer]}}} @self"])
        out += skill(f"BLAZE_CHOIR_{s}_SHIELD", [f"  - state{{m={m};s=shield}} @self", "  - sound{s=block.beacon.activate;v=1;p=1.6} @self"]
                     + tints(singer, STATES[singer]["BANKED"]))
        out += skill(f"BLAZE_CHOIR_{s}_UNSHIELD", [f"  - state{{m={m};s=unshield}} @self"])
        out += skill(f"BLAZE_CHOIR_{s}_CHORUS", [f"  - state{{m={m};s=chorus}} @self", f"  - sound{{s={SING_SOUND[singer]}}} @self",
                                                 "  - delay 30", f"  - sound{{s={SING_SOUND[singer]}}} @self"])
        out += skill(f"BLAZE_CHOIR_{s}_LAST", [f"  - defaultstate{{m={m};t=idle;s=last}} @self"])
        out += skill(f"BLAZE_CHOIR_{s}_FLINCH", [f"  - state{{m={m};s=flinch}} @self"])
        for state, colour in STATES[singer].items():
            out += skill(f"BLAZE_CHOIR_{s}_STATE_{state}", tints(singer, colour))
        out += skill(f"BLAZE_CHOIR_{s}_DEATH", [f"  - sound{{s=entity.blaze.death;v=2;p=0.7}} @self"] + tints(singer, DEAD))
    return "\n".join(out)


def mobs():
    out = ["# The Blaze Choir's three bodies: each singer's model on an invisible blaze. Occultech decides every orbit, shield,",
           "# fireball and chorus, deals all damage (BlazeChoir.java) and hands out loot. Health is the solo value;",
           "# Occultech multiplies it for the group after the spawn.", ""]
    for singer in SINGERS:
        s, m = singer.upper(), f"occultech_blaze_choir_{singer}"
        out += [f"OCCULTECH_BLAZE_CHOIR_{s}:", "  Type: BLAZE", f"  Display: '&6Blaze Choir &7({singer.capitalize()})'",
                "  Health: 110", "  Damage: 0", "  Armor: 0", "  Options:",
                "    # Occultech rebuilds the choir from its saved fight state; Mythic never restores it",
                "    Despawn: true", "    PreventOtherDrops: true", "    PreventMobKillDrops: true", "    PreventItemPickup: true",
                "    KnockbackResistance: 1", "    FollowRange: 32", "    Silent: true", "    AlwaysShowName: true", "  Drops: []",
                "  Skills:", f"  - model{{m={m}}} @self ~onSpawn", f"  - state{{m={m};s=spawn}} @self ~onSpawn",
                "  - bodyrotation{mh=40;mnh=-40;rde=0;rdu=3} @self ~onSpawn",
                f"  - skill{{s=BLAZE_CHOIR_{s}_STATE_CALM}} @self ~onSpawn",
                f"  - skill{{s=BLAZE_CHOIR_{s}_DEATH}} @self ~onDeath", ""]
    return "\n".join(out)


def main():
    print(json.dumps(ship(), indent=1))
    SKILLS.write_text(skills(), encoding="utf-8")
    MOBS.write_text(mobs(), encoding="utf-8")


if __name__ == "__main__":
    main()
