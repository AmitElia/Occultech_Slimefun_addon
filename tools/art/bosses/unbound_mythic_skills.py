"""The Unbound, session 8: writes his cosmetic Mythic skills (src/main/mythic/Skills/TheUnbound.yml).

Look and sound only: TheUnbound.java decides when each skill runs and deals every hit. The fire's stages are
BetterModel tints over the near-white fire (session 6) on glow_chest and glow_flames, with glow_flames shown from
the burning stage; each is re-applied 12 ticks later, after any hit flash (BetterModel restores a bone's previous
tint when a flash ends).

Run from the repository root: python tools/art/bosses/unbound_mythic_skills.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "src/main/mythic/Skills/TheUnbound.yml"
M = "occultech_the_unbound"
STAGES = {"EMBERS": ("C82C0E", False), "BURNING": ("FF9618", True), "INFERNO": ("50D6FF", True)}
SATED, DEAD = "6E2414", "281E1C"


def fire(colour, flames):
    out = [f"  - tint{{m={M};p=glow_chest;c={colour}}} @self", f"  - tint{{m={M};p=glow_flames;c={colour}}} @self"]
    out.append(f"  - partvisibility{{m={M};p=glow_flames;v={'true' if flames else 'false'}}} @self")
    return out


def skills():
    out = ["# Look and sound only. TheUnbound.java decides when each of these runs and deals every hit.",
           "# Generated by tools/art/bosses/unbound_mythic_skills.py.",
           "# The fire's stages are BetterModel tints over the near-white fire: embers C82C0E (deep red), burning",
           "# FF9618 (orange, flames shown), inferno 50D6FF (spirit fire, flames shown), sated coals 6E2414, dead",
           "# 281E1C. The sparks, smoke and flames pouring out of his furnace are drawn by the plugin, more at each stage.", ""]
    for stage, (colour, flames) in STAGES.items():
        # at once: his spawn, a fight resumed, the end of the sated opening
        out += [f"THE_UNBOUND_STAGE_{stage}:", "  Skills:"] + fire(colour, flames)
        out += ["  - delay 12"] + fire(colour, flames)
        if stage != "EMBERS":
            # the stage change: a short roar as the fire flares
            out += [f"THE_UNBOUND_ENRAGE_{stage}:", "  Skills:", f"  - state{{m={M};s=enrage}} @self",
                    "  - sound{s=entity.ravager.roar;v=1.6;p=0.8} @self", "  - delay 8"] + fire(colour, flames)
            flame = "soul_fire_flame" if stage == "INFERNO" else "flame"
            out += [f"  - particles{{p={flame};a=60;hs=0.8;vs=0.9;s=0.09;y=3.0}} @self",
                    "  - particles{p=lava;a=16;hs=0.6;vs=0.5;y=3.0} @self",
                    "  - particles{p=large_smoke;a=20;hs=0.7;vs=0.6;s=0.03;y=3.6} @self",
                    "  - sound{s=block.fire.extinguish;v=1.4;p=0.5} @self", "  - delay 12"] + fire(colour, flames)
    out += ["THE_UNBOUND_CLEAVE:", "  Skills:", f"  - state{{m={M};s=cleave}} @self",
            "  - sound{s=entity.vindicator.celebrate;v=1.4;p=0.5} @self",
            "  - delay 26", "  - sound{s=entity.player.attack.sweep;v=2;p=0.6} @self",
            "  - particles{p=sweep_attack;a=4;hs=1.6;vs=0.3;y=1.0;fo=3} @self",
            "THE_UNBOUND_CALL:", "  Skills:", f"  - state{{m={M};s=call}} @self", "  - delay 16",
            "  - sound{s=entity.ravager.roar;v=2;p=0.6} @self", "  - particles{p=large_smoke;a=20;hs=1.2;vs=0.2;y=0.2} @self",
            "THE_UNBOUND_DEVOUR:", "  Skills:", f"  - state{{m={M};s=devour}} @self", "  - delay 16",
            "  - sound{s=entity.generic.eat;v=2;p=0.6} @self",
            "THE_UNBOUND_SATED:", "  Skills:", f"  - state{{m={M};s=sated}} @self"] + fire(SATED, False)
    out += ["  - particles{p=large_smoke;a=24;hs=0.5;vs=0.4;s=0.02;y=2.6} @self", "  - delay 12"] + fire(SATED, False)
    out += ["THE_UNBOUND_FLINCH:", "  Skills:", f"  - state{{m={M};s=flinch}} @self",
            "THE_UNBOUND_SWING:", "  Skills:", f"  - state{{m={M};s=swing}} @self",
            "THE_UNBOUND_DEATH:", "  Skills:", f"  - state{{m={M};s=death}} @self"] + fire(DEAD, False)
    out += ["  - sound{s=entity.vindicator.death;v=1.6;p=0.6} @self",
            "  - particles{p=large_smoke;a=36;hs=0.8;vs=0.8;s=0.02;y=2.6} @self", ""]
    return "\n".join(out)


if __name__ == "__main__":
    OUT.write_text(skills(), encoding="utf-8")
    print(OUT)
